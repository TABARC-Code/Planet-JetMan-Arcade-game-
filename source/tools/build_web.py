"""Build the browser edition.

  web/assets.js            - assets/ embedded as base64 data URLs (so the game also works from file://)
  dist_web/index.html      - single self-contained file (HTML + JS + assets), ready to host or double-click
  dist_web/CREDITS.txt
"""
import base64
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'assets')
WEB = os.path.join(ROOT, 'web')
DIST = os.path.join(ROOT, 'dist_web')


def data_url(path, mime):
    with open(path, 'rb') as fh:
        return 'data:%s;base64,%s' % (mime, base64.b64encode(fh.read()).decode('ascii'))


img, icon = {}, {}
for name in sorted(os.listdir(ASSETS)):
    stem, ext = os.path.splitext(name)
    if stem == 'explosion':
        continue  # superseded by the ansimuz strips
    if ext == '.png':
        img[stem] = data_url(os.path.join(ASSETS, name), 'image/png')
    elif ext == '.svg':
        icon[stem] = data_url(os.path.join(ASSETS, name), 'image/svg+xml')
    # .wav files are reference material only - sounds are code now (web/sfx.js, web/music.js)


def js_obj(d):
    return '{\n' + ''.join('    "%s": "%s",\n' % (k, v) for k, v in d.items()) + '  }'


assets_js = ('// Generated by tools/build_web.py - third-party assets, see CREDITS.txt\n'
             "'use strict';\nconst ASSET_DATA = {\n  img: %s,\n  icon: %s,\n};\n"
             % (js_obj(img), js_obj(icon)))
with open(os.path.join(WEB, 'assets.js'), 'w', encoding='utf-8') as fh:
    fh.write(assets_js)

with open(os.path.join(WEB, 'index.html'), encoding='utf-8') as fh:
    html = fh.read()
parts = []
for f in ('assets.js', 'game.js', 'sfx.js', 'music.js', 'input.js', 'main.js'):
    with open(os.path.join(WEB, f), encoding='utf-8') as fh:
        parts.append('<script>\n%s\n</script>' % fh.read().replace('</script', '<\\/script'))
single = re.sub(r'<!--SCRIPTS-->.*?<!--/SCRIPTS-->', lambda m: '\n'.join(parts), html, flags=re.S)
os.makedirs(DIST, exist_ok=True)
with open(os.path.join(DIST, 'index.html'), 'w', encoding='utf-8') as fh:
    fh.write(single)
shutil.copy(os.path.join(ASSETS, 'CREDITS.txt'), os.path.join(DIST, 'CREDITS.txt'))
print('web build: %d KB single file -> %s' % (len(single.encode()) // 1024, os.path.join(DIST, 'index.html')))
